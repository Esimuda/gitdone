import type { Sql } from "./sql";

const USERS = `
CREATE TABLE IF NOT EXISTS users (
  gitlab_user_id TEXT PRIMARY KEY,
  username TEXT NOT NULL,
  name TEXT NOT NULL,
  avatar_url TEXT,
  token_ciphertext TEXT NOT NULL,
  token_iv TEXT NOT NULL,
  token_tag TEXT NOT NULL,
  refresh_ciphertext TEXT,
  refresh_iv TEXT,
  refresh_tag TEXT,
  token_expires_at TEXT,
  updated_at TEXT NOT NULL
)`;

const SESSIONS = `
CREATE TABLE IF NOT EXISTS sessions (
  id TEXT PRIMARY KEY,
  gitlab_user_id TEXT NOT NULL,
  pending_project TEXT,
  expires_at TEXT NOT NULL
)`;

const OAUTH = `
CREATE TABLE IF NOT EXISTS oauth_states (
  state TEXT PRIMARY KEY,
  code_verifier TEXT,
  next_path TEXT,
  expires_at TEXT NOT NULL
)`;

const RATE = `
CREATE TABLE IF NOT EXISTS rate_hits (
  bucket TEXT NOT NULL,
  at_ms BIGINT NOT NULL
)`;

function projects(dialect: Sql["dialect"]): string {
  const id = dialect === "postgres" ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";
  return `
CREATE TABLE IF NOT EXISTS projects (
  id ${id},
  gitlab_project_id TEXT NOT NULL UNIQUE,
  path TEXT NOT NULL,
  name TEXT NOT NULL,
  web_url TEXT NOT NULL,
  owner_gitlab_user_id TEXT NOT NULL,
  token_ciphertext TEXT NOT NULL,
  token_iv TEXT NOT NULL,
  token_tag TEXT NOT NULL,
  merge_request_url TEXT,
  merge_request_iid INTEGER,
  is_public INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
)`;
}

const ADDITIONS = [
  "ALTER TABLE users ADD COLUMN avatar_url TEXT",
  "ALTER TABLE users ADD COLUMN refresh_ciphertext TEXT",
  "ALTER TABLE users ADD COLUMN refresh_iv TEXT",
  "ALTER TABLE users ADD COLUMN refresh_tag TEXT",
  "ALTER TABLE users ADD COLUMN token_expires_at TEXT",
  "ALTER TABLE oauth_states ADD COLUMN code_verifier TEXT",
  "ALTER TABLE oauth_states ADD COLUMN next_path TEXT",
  "ALTER TABLE projects ADD COLUMN merge_request_iid INTEGER",
  "ALTER TABLE projects ADD COLUMN is_public INTEGER NOT NULL DEFAULT 0",
];

export async function migrate(sql: Sql): Promise<void> {
  await sql.exec(USERS);
  await sql.exec(SESSIONS);
  await sql.exec(OAUTH);
  await sql.exec(projects(sql.dialect));
  await sql.exec(RATE);
  for (const statement of ADDITIONS) {
    try {
      await sql.exec(statement);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      if (/duplicate column|already exists/i.test(message)) continue;
      throw error;
    }
  }
}
